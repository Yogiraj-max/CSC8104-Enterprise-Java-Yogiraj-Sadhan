package uk.ac.newcastle.enterprisemiddleware.customer;

import org.eclipse.microprofile.openapi.annotations.Operation;
import org.eclipse.microprofile.openapi.annotations.media.Schema;
import org.eclipse.microprofile.openapi.annotations.parameters.Parameter;
import org.eclipse.microprofile.openapi.annotations.responses.APIResponse;
import org.eclipse.microprofile.openapi.annotations.responses.APIResponses;
import org.eclipse.microprofile.openapi.annotations.tags.Tag;
import uk.ac.newcastle.enterprisemiddleware.util.RestServiceException;
import uk.ac.newcastle.enterprisemiddleware.util.ViolationReasons;

import javax.inject.Inject;
import javax.inject.Named;
import javax.transaction.Transactional;
import javax.validation.ConstraintViolationException;
import javax.ws.rs.*;
import javax.ws.rs.core.MediaType;
import javax.ws.rs.core.Response;
import java.util.logging.Logger;

/**
 * REST endpoints for Customers: create, list, get by id and delete.
 * Deleting a Customer also deletes all of their Bookings (JPA cascade).
 */
@Path("/customers")
@Consumes(MediaType.APPLICATION_JSON)
@Produces(MediaType.APPLICATION_JSON)
@Tag(name = "Customers", description = "Create, list and delete customers of the flight booking service")
public class CustomerRestService {

    @Inject
    @Named("logger")
    Logger log;

    @Inject
    CustomerService service;

    @GET
    @Operation(summary = "List all Customers", description = "Returns a JSON array of every Customer, ordered by name.")
    @APIResponses({
            @APIResponse(responseCode = "200", description = "List of Customers (may be empty)")
    })
    public Response retrieveAllCustomers() {
        return Response.ok(service.findAllOrderedByName()).build();
    }

    @GET
    @Path("/{id:[0-9]+}")
    @Operation(summary = "Fetch a Customer by id", description = "Returns the Customer with the given id.")
    @APIResponses({
            @APIResponse(responseCode = "200", description = "Customer found"),
            @APIResponse(responseCode = "404", description = "No Customer with this id exists")
    })
    public Response retrieveCustomerById(
            @Parameter(description = "Id of the Customer to fetch", required = true)
            @Schema(minimum = "0")
            @PathParam("id") long id) {
        Customer customer = service.findById(id);
        if (customer == null) {
            throw new RestServiceException("No Customer with the id " + id + " was found!", Response.Status.NOT_FOUND);
        }
        return Response.ok(customer).build();
    }

    @POST
    @Operation(summary = "Create a Customer",
            description = "Creates a Customer from the JSON body. The id is generated by the service; any id sent is ignored. "
                    + "Example body: {\"name\":\"Jane Doe\",\"email\":\"jane@example.com\",\"phoneNumber\":\"07123456789\"}")
    @APIResponses({
            @APIResponse(responseCode = "201", description = "Customer created; the body contains the new Customer including its id"),
            @APIResponse(responseCode = "400", description = "Body missing, or a field is invalid (name not alphabetic / too long, bad email, phone not 0 + 10 digits)"),
            @APIResponse(responseCode = "409", description = "A Customer with this email already exists"),
            @APIResponse(responseCode = "500", description = "Unexpected error whilst processing the request")
    })
    @Transactional
    public Response createCustomer(
            @Parameter(description = "JSON representation of the Customer to create", required = true)
            Customer customer) {

        if (customer == null) {
            throw new RestServiceException("Bad Request", Response.Status.BAD_REQUEST);
        }
        try {
            service.create(customer);
        } catch (ConstraintViolationException ce) {
            throw new RestServiceException("Bad Request", ViolationReasons.of(ce), Response.Status.BAD_REQUEST, ce);
        } catch (UniqueEmailException e) {
            throw new RestServiceException("Conflict",
                    ViolationReasons.single("email", "That email is already used, please use a unique email"),
                    Response.Status.CONFLICT, e);
        } catch (Exception e) {
            throw new RestServiceException(e);
        }
        log.info("createCustomer completed. Customer = " + customer);
        return Response.status(Response.Status.CREATED).entity(customer).build();
    }

    @DELETE
    @Path("/{id:[0-9]+}")
    @Operation(summary = "Delete a Customer", description = "Deletes the Customer and, through a JPA cascade, every Booking they made.")
    @APIResponses({
            @APIResponse(responseCode = "204", description = "Customer (and their Bookings) deleted"),
            @APIResponse(responseCode = "404", description = "No Customer with this id exists"),
            @APIResponse(responseCode = "500", description = "Unexpected error whilst processing the request")
    })
    @Transactional
    public Response deleteCustomer(
            @Parameter(description = "Id of the Customer to delete", required = true)
            @Schema(minimum = "0")
            @PathParam("id") long id) {
        Customer customer = service.findById(id);
        if (customer == null) {
            throw new RestServiceException("No Customer with the id " + id + " was found!", Response.Status.NOT_FOUND);
        }
        try {
            service.delete(customer);
        } catch (Exception e) {
            throw new RestServiceException(e);
        }
        log.info("deleteCustomer completed. Customer = " + customer);
        return Response.noContent().build();
    }
}
