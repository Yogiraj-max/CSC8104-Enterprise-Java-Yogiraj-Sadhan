package uk.ac.newcastle.enterprisemiddleware.flight;

import com.fasterxml.jackson.annotation.JsonIgnore;
import org.eclipse.microprofile.openapi.annotations.media.Schema;
import uk.ac.newcastle.enterprisemiddleware.booking.Booking;

import javax.persistence.*;
import javax.validation.constraints.AssertTrue;
import javax.validation.constraints.NotNull;
import javax.validation.constraints.Pattern;
import java.io.Serializable;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/**
 * A Flight that Customers can book: a flight number, a point of departure and a destination.
 *
 * Bookings for the flight are mapped with @OneToMany. CascadeType.REMOVE (plus orphanRemoval) means
 * that deleting a Flight automatically deletes every Booking made for it.
 */
@Entity
@NamedQueries({
        @NamedQuery(name = Flight.FIND_ALL, query = "SELECT f FROM Flight f ORDER BY f.flightNumber ASC"),
        @NamedQuery(name = Flight.FIND_BY_NUMBER, query = "SELECT f FROM Flight f WHERE f.flightNumber = :flightNumber")
})
@Table(name = "flight", uniqueConstraints = @UniqueConstraint(columnNames = "flight_number"))
public class Flight implements Serializable {

    private static final long serialVersionUID = 1L;

    public static final String FIND_ALL = "Flight.findAll";
    public static final String FIND_BY_NUMBER = "Flight.findByNumber";

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Schema(readOnly = true, description = "Generated by the service. Any value supplied by the client is ignored.")
    private Long id;

    @NotNull
    @Pattern(regexp = "^[A-Za-z0-9]{5}$", message = "Flight number must be exactly 5 letters or digits")
    @Column(name = "flight_number")
    @Schema(example = "BA123")
    private String flightNumber;

    @NotNull
    @Pattern(regexp = "^[A-Z]{3}$", message = "Departure must be exactly 3 upper-case letters (e.g. NCL)")
    @Column(name = "departure")
    @Schema(example = "NCL")
    private String departure;

    @NotNull
    @Pattern(regexp = "^[A-Z]{3}$", message = "Destination must be exactly 3 upper-case letters (e.g. LHR)")
    @Column(name = "destination")
    @Schema(example = "LHR")
    private String destination;

    @JsonIgnore
    @OneToMany(mappedBy = "flight", cascade = CascadeType.REMOVE, orphanRemoval = true, fetch = FetchType.LAZY)
    private List<Booking> bookings = new ArrayList<>();

    /**
     * Cross-field rule: a flight cannot depart from and arrive at the same airport.
     * Null values are left to the @NotNull checks above.
     */
    @JsonIgnore
    @AssertTrue(message = "Destination must be different from the point of departure")
    public boolean isDestinationDifferentFromDeparture() {
        return departure == null || destination == null || !departure.equals(destination);
    }

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getFlightNumber() { return flightNumber; }
    public void setFlightNumber(String flightNumber) { this.flightNumber = flightNumber; }

    public String getDeparture() { return departure; }
    public void setDeparture(String departure) { this.departure = departure; }

    public String getDestination() { return destination; }
    public void setDestination(String destination) { this.destination = destination; }

    public List<Booking> getBookings() { return bookings; }
    public void setBookings(List<Booking> bookings) { this.bookings = bookings; }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Flight)) return false;
        return Objects.equals(flightNumber, ((Flight) o).flightNumber);
    }

    @Override
    public int hashCode() { return Objects.hash(flightNumber); }

    @Override
    public String toString() {
        return "Flight{id=" + id + ", flightNumber='" + flightNumber + "', departure='" + departure
                + "', destination='" + destination + "'}";
    }
}
