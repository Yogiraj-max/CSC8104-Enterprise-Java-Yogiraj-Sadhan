package uk.ac.newcastle.enterprisemiddleware.flight;

import org.eclipse.microprofile.openapi.annotations.Operation;
import org.eclipse.microprofile.openapi.annotations.media.Schema;
import org.eclipse.microprofile.openapi.annotations.parameters.Parameter;
import org.eclipse.microprofile.openapi.annotations.responses.APIResponse;
import org.eclipse.microprofile.openapi.annotations.responses.APIResponses;
import org.eclipse.microprofile.openapi.annotations.tags.Tag;
import uk.ac.newcastle.enterprisemiddleware.util.RestServiceException;
import uk.ac.newcastle.enterprisemiddleware.util.ViolationReasons;

import javax.inject.Inject;
import javax.inject.Named;
import javax.transaction.Transactional;
import javax.validation.ConstraintViolationException;
import javax.ws.rs.*;
import javax.ws.rs.core.MediaType;
import javax.ws.rs.core.Response;
import java.util.logging.Logger;

/**
 * REST endpoints for Flights (the commodity): create, list, get by id and delete.
 * Deleting a Flight also deletes all Bookings made for it (JPA cascade).
 */
@Path("/flights")
@Consumes(MediaType.APPLICATION_JSON)
@Produces(MediaType.APPLICATION_JSON)
@Tag(name = "Flights", description = "Create, list and delete flights that can be booked")
public class FlightRestService {

    @Inject
    @Named("logger")
    Logger log;

    @Inject
    FlightService service;

    @GET
    @Operation(summary = "List all Flights", description = "Returns a JSON array of every Flight, ordered by flight number.")
    @APIResponses({
            @APIResponse(responseCode = "200", description = "List of Flights (may be empty)")
    })
    public Response retrieveAllFlights() {
        return Response.ok(service.findAllOrderedByNumber()).build();
    }

    @GET
    @Path("/{id:[0-9]+}")
    @Operation(summary = "Fetch a Flight by id", description = "Returns the Flight with the given id.")
    @APIResponses({
            @APIResponse(responseCode = "200", description = "Flight found"),
            @APIResponse(responseCode = "404", description = "No Flight with this id exists")
    })
    public Response retrieveFlightById(
            @Parameter(description = "Id of the Flight to fetch", required = true)
            @Schema(minimum = "0")
            @PathParam("id") long id) {
        Flight flight = service.findById(id);
        if (flight == null) {
            throw new RestServiceException("No Flight with the id " + id + " was found!", Response.Status.NOT_FOUND);
        }
        return Response.ok(flight).build();
    }

    @POST
    @Operation(summary = "Create a Flight",
            description = "Creates a Flight from the JSON body. The id is generated by the service; any id sent is ignored. "
                    + "Example body: {\"flightNumber\":\"BA123\",\"departure\":\"NCL\",\"destination\":\"LHR\"}")
    @APIResponses({
            @APIResponse(responseCode = "201", description = "Flight created; the body contains the new Flight including its id"),
            @APIResponse(responseCode = "400", description = "Body missing, or a field is invalid (flight number not 5 alphanumerics, "
                    + "departure/destination not 3 upper-case letters, or destination equal to departure)"),
            @APIResponse(responseCode = "409", description = "A Flight with this flight number already exists"),
            @APIResponse(responseCode = "500", description = "Unexpected error whilst processing the request")
    })
    @Transactional
    public Response createFlight(
            @Parameter(description = "JSON representation of the Flight to create", required = true)
            Flight flight) {

        if (flight == null) {
            throw new RestServiceException("Bad Request", Response.Status.BAD_REQUEST);
        }
        try {
            service.create(flight);
        } catch (ConstraintViolationException ce) {
            throw new RestServiceException("Bad Request", ViolationReasons.of(ce), Response.Status.BAD_REQUEST, ce);
        } catch (UniqueFlightNumberException e) {
            throw new RestServiceException("Conflict",
                    ViolationReasons.single("flightNumber", "That flight number is already used, please use a unique flight number"),
                    Response.Status.CONFLICT, e);
        } catch (Exception e) {
            throw new RestServiceException(e);
        }
        log.info("createFlight completed. Flight = " + flight);
        return Response.status(Response.Status.CREATED).entity(flight).build();
    }

    @DELETE
    @Path("/{id:[0-9]+}")
    @Operation(summary = "Delete a Flight", description = "Deletes the Flight and, through a JPA cascade, every Booking made for it.")
    @APIResponses({
            @APIResponse(responseCode = "204", description = "Flight (and its Bookings) deleted"),
            @APIResponse(responseCode = "404", description = "No Flight with this id exists"),
            @APIResponse(responseCode = "500", description = "Unexpected error whilst processing the request")
    })
    @Transactional
    public Response deleteFlight(
            @Parameter(description = "Id of the Flight to delete", required = true)
            @Schema(minimum = "0")
            @PathParam("id") long id) {
        Flight flight = service.findById(id);
        if (flight == null) {
            throw new RestServiceException("No Flight with the id " + id + " was found!", Response.Status.NOT_FOUND);
        }
        try {
            service.delete(flight);
        } catch (Exception e) {
            throw new RestServiceException(e);
        }
        log.info("deleteFlight completed. Flight = " + flight);
        return Response.noContent().build();
    }
}
