package uk.ac.newcastle.enterprisemiddleware.booking;

import com.fasterxml.jackson.annotation.JsonProperty;
import org.eclipse.microprofile.openapi.annotations.media.Schema;
import uk.ac.newcastle.enterprisemiddleware.customer.Customer;
import uk.ac.newcastle.enterprisemiddleware.flight.Flight;

import javax.persistence.*;
import javax.validation.constraints.Future;
import javax.validation.constraints.NotNull;
import java.io.Serializable;
import java.time.LocalDate;
import java.util.Objects;

/**
 * A Booking links a Customer to a Flight on a particular (future) date.
 *
 * Relationships are real JPA @ManyToOne associations, so deleting a Customer or Flight cascades to its Bookings
 * (the cascade is declared on the @OneToMany side in Customer and Flight).
 *
 * JSON shape:
 *   request  -> {"customerId": 1, "flightId": 2, "bookingDate": "2027-01-15"}
 *   response -> the same, plus "id" and the full "customer" and "flight" objects (read-only).
 *
 * Only one booking may exist for a given flight on a given date (unique constraint on flight_id + booking_date).
 */
@Entity
@NamedQueries({
        @NamedQuery(name = Booking.FIND_ALL, query = "SELECT b FROM Booking b ORDER BY b.bookingDate ASC, b.id ASC"),
        @NamedQuery(name = Booking.FIND_BY_CUSTOMER,
                query = "SELECT b FROM Booking b WHERE b.customer.id = :customerId ORDER BY b.bookingDate ASC, b.id ASC"),
        @NamedQuery(name = Booking.FIND_BY_FLIGHT_AND_DATE,
                query = "SELECT b FROM Booking b WHERE b.flight.id = :flightId AND b.bookingDate = :bookingDate")
})
@Table(name = "booking", uniqueConstraints = @UniqueConstraint(columnNames = {"flight_id", "booking_date"}))
public class Booking implements Serializable {

    private static final long serialVersionUID = 1L;

    public static final String FIND_ALL = "Booking.findAll";
    public static final String FIND_BY_CUSTOMER = "Booking.findByCustomer";
    public static final String FIND_BY_FLIGHT_AND_DATE = "Booking.findByFlightAndDate";

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Schema(readOnly = true, description = "Generated by the service. Any value supplied by the client is ignored.")
    private Long id;

    @NotNull(message = "A valid customerId must be supplied")
    @ManyToOne(fetch = FetchType.EAGER, optional = false)
    @JoinColumn(name = "customer_id", nullable = false)
    @JsonProperty(access = JsonProperty.Access.READ_ONLY)
    @Schema(readOnly = true)
    private Customer customer;

    @NotNull(message = "A valid flightId must be supplied")
    @ManyToOne(fetch = FetchType.EAGER, optional = false)
    @JoinColumn(name = "flight_id", nullable = false)
    @JsonProperty(access = JsonProperty.Access.READ_ONLY)
    @Schema(readOnly = true)
    private Flight flight;

    @NotNull(message = "A booking date must be supplied")
    @Future(message = "The booking date must be in the future")
    @Column(name = "booking_date", nullable = false)
    @Schema(example = "2027-01-15", description = "Date of travel in yyyy-MM-dd format; must be in the future")
    private LocalDate bookingDate;

    // Ids sent by the client. Not stored as columns - the service resolves them into the real Customer/Flight.
    @Transient
    @Schema(example = "1", description = "Id of an existing Customer")
    private Long customerId;

    @Transient
    @Schema(example = "1", description = "Id of an existing Flight")
    private Long flightId;

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public Customer getCustomer() { return customer; }
    public void setCustomer(Customer customer) { this.customer = customer; }

    public Flight getFlight() { return flight; }
    public void setFlight(Flight flight) { this.flight = flight; }

    public LocalDate getBookingDate() { return bookingDate; }
    public void setBookingDate(LocalDate bookingDate) { this.bookingDate = bookingDate; }

    public Long getCustomerId() { return customer != null ? customer.getId() : customerId; }
    public void setCustomerId(Long customerId) { this.customerId = customerId; }

    public Long getFlightId() { return flight != null ? flight.getId() : flightId; }
    public void setFlightId(Long flightId) { this.flightId = flightId; }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Booking)) return false;
        Booking other = (Booking) o;
        return id != null && Objects.equals(id, other.id);
    }

    @Override
    public int hashCode() { return getClass().hashCode(); }

    @Override
    public String toString() {
        return "Booking{id=" + id + ", customerId=" + getCustomerId() + ", flightId=" + getFlightId()
                + ", bookingDate=" + bookingDate + "}";
    }
}
